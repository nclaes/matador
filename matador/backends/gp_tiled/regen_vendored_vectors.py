#!/usr/bin/env python3
"""Regenerate vectors/{gp_stimulus,gp_expected,gp_small_load,gp_small_infer}.memh
and gp_sizes.vh for tb_system_gp.v, after the CMD_LOAD word1 layout changed
(clauses_per_class widened from 8 to 16 bits, threshold retired -- see
tm_accel_gp.v's header comment).

tm_emulator.py's own `genvec` subcommand can't be used for this: it depends
on extract_rom_model() parsing a frozen tm_accelerator.v + tb_system.v pair
that were never vendored into this repo (a pre-existing gap, unrelated to
the word1 change) -- `python3 tm_emulator.py genvec` fails immediately with
FileNotFoundError before writing anything. This script reproduces the same
scenario shape genvec describes (P0 LOAD "frozen"-equivalent model, P1 INFER
batch, P2 LOAD "small" model, P3 INFER batch, P4 LOAD "frozen"-equivalent
again, P5 INFER single frame) using two seeded random_model() instances
matching genvec's own geometry defaults, since tb_system_gp.v's suite only
checks wire-protocol conformance (framing, LOAD ack, INFER classify-matches-
emulator, error injection/recovery) -- not real trained-model accuracy -- so
a random-but-valid model is functionally equivalent to the missing frozen
ROM for this purpose. Run once, from this directory (matador/backends/gp_tiled/):
    python3 regen_vendored_vectors.py
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "vendor"))
import tm_emulator as te  # noqa: E402

HERE = Path(__file__).parent / "vendor"
OUT = HERE / "vectors"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(2026)

    # "frozen"-equivalent: matches extract_rom_model()'s hardcoded shape
    # (n_features=512, n_classes=10, clauses_per_class=20) so the packet
    # sizes/timing this fixture exercises stay representative.
    frozen = te.random_model(rng, n_features=512, n_classes=10,
                              clauses_per_class=20, include_density=0.02,
                              name="frozen_equiv")
    feats = [rng.getrandbits(frozen.n_features) for _ in range(10)]

    # "small": matches genvec's own CLI defaults exactly.
    small = te.random_model(rng, n_features=96, n_classes=4,
                             clauses_per_class=8, include_density=0.06,
                             name="small")
    small_vecs = [rng.getrandbits(small.n_features) for _ in range(6)]

    packets = [
        te.encode_load_packet(frozen),
        te.encode_infer_packet(frozen, feats),
        te.encode_load_packet(small),
        te.encode_infer_packet(small, small_vecs),
        te.encode_load_packet(frozen),
        te.encode_infer_packet(frozen, [feats[0]]),
    ]
    s_words, s_lasts = te.stream_with_tlast(packets)

    exp_words, exp_lasts = [], []

    def add(w: int, l: int) -> None:
        exp_words.append(w)
        exp_lasts.append(l)

    add(te.expected_load_ack(frozen), 1)
    for i, fv in enumerate(feats):
        pred, _ = frozen.infer(fv)
        add(pred, 1 if i == len(feats) - 1 else 0)
    add(te.expected_load_ack(small), 1)
    for i, fv in enumerate(small_vecs):
        pred, _ = small.infer(fv)
        add(pred, 1 if i == len(small_vecs) - 1 else 0)
    add(te.expected_load_ack(frozen), 1)
    pred0, _ = frozen.infer(feats[0])
    add(pred0, 1)

    te.write_memh(OUT / "gp_stimulus.memh", s_words, s_lasts)
    te.write_memh(OUT / "gp_expected.memh", exp_words, exp_lasts)

    sl_words, sl_lasts = te.stream_with_tlast([te.encode_load_packet(small)])
    te.write_memh(OUT / "gp_small_load.memh", sl_words, sl_lasts)
    si_words, si_lasts = te.stream_with_tlast(
        [te.encode_infer_packet(small, [small_vecs[0]])])
    te.write_memh(OUT / "gp_small_infer.memh", si_words, si_lasts)
    small_pred0, _ = small.infer(small_vecs[0])

    (OUT / "gp_sizes.vh").write_text(
        f"// generated by regen_vendored_vectors.py (seed=2026)\n"
        f"localparam GP_N_STIM         = {len(s_words)};\n"
        f"localparam GP_N_EXP          = {len(exp_words)};\n"
        f"localparam GP_N_SMALL        = {len(sl_words)};\n"
        f"localparam GP_N_SMALL_INFER  = {len(si_words)};\n"
        f"localparam GP_SMALL_NBEATS   = {small.n_beats};\n"
        f"localparam [31:0] GP_SMALL_ACK       = 32'h{te.expected_load_ack(small):08X};\n"
        f"localparam [31:0] GP_SMALL_INFER_EXP = 32'h{small_pred0:08X};\n"
    )
    print(f"wrote {len(s_words)} stimulus beats, {len(exp_words)} expected beats -> {OUT}")


if __name__ == "__main__":
    main()
