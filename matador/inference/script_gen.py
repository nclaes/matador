# Step 3 — Build the provenance report
# ---------------------------------------------------------------------------

def build_provenance_report(include_matrix, meta, test_data_path: Path, model_source: str):
    """Run inference on the full test dataset and compile a provenance report.

    Loads the test data (space-separated Boolean values, last column = class label),
    runs run_inference(), and collects accuracy, per-class breakdown, confusion
    matrix, model fingerprint, and dataset SHA-256 into a dict that can be
    written as JSON.

    You can call run_inference() and this function independently if you want
    to reuse the inference logic without generating the full report.
    """
    # Load test data: each row is a sample, last column is the class label
    raw    = np.genfromtxt(str(test_data_path), delimiter=" ", dtype=np.uint32)
    X_test = raw[:, :-1].astype(np.uint8)   # feature columns
    y_test = raw[:, -1 ].astype(np.int64)   # label column

    # Hash the dataset file so anyone can verify they have the same split
    data_sha256 = hashlib.sha256(test_data_path.read_bytes()).hexdigest()

    # Run inference from the ROM (same algorithm as the RTL)
    predictions, scores = run_inference(include_matrix, X_test)

    correct      = predictions == y_test
    n_correct    = int(correct.sum())
    n_total      = len(y_test)
    accuracy_pct = round(100.0 * n_correct / n_total, 4) if n_total else 0.0

    # Per-class accuracy breakdown
    n_classes = include_matrix.shape[0]
    per_class = {{}}
    for cls in sorted(int(c) for c in np.unique(y_test)):
        cls_mask    = y_test == cls
        cls_total   = int(cls_mask.sum())
        cls_correct = int((correct & cls_mask).sum())
        per_class[str(cls)] = {{
            "correct":      cls_correct,
            "total":        cls_total,
            "accuracy_pct": round(100.0 * cls_correct / cls_total, 4) if cls_total else 0.0,
        }}

    # Confusion matrix: rows = true class, columns = predicted class
    confusion = np.zeros((n_classes, n_classes), dtype=np.int64)
    for true_cls, pred_cls in zip(y_test, predictions):
        if 0 <= int(true_cls) < n_classes and 0 <= int(pred_cls) < n_classes:
            confusion[int(true_cls), int(pred_cls)] += 1

    return {{
        "generated_at":        datetime.now(timezone.utc).isoformat(),
        "python_version":      platform.python_version(),
        "platform":            platform.platform(),
        "model_source":        model_source,
        "model_fingerprint":   meta.get("model_fingerprint", ""),
        "model_variant":       meta.get("model_variant", ""),
        "n_features":          meta.get("n_features",          include_matrix.shape[2] // 2),
        "n_classes":           meta.get("n_classes",           include_matrix.shape[0]),
        "n_clauses_total":     meta.get("n_clauses_total",     include_matrix.shape[0] * include_matrix.shape[1]),
        "n_clauses_per_class": meta.get("n_clauses_per_class", include_matrix.shape[1]),
        "hyperparameters":     meta.get("hyperparameters", {{}}),
        "provenance":          meta.get("provenance",      {{}}),
        "test_data_path":      str(test_data_path.resolve()),
        "test_data_sha256":    data_sha256,
        "n_samples":           n_total,
        "inference_engine":    "Pure NumPy — ROM-equivalent (Include-action matrix, no tmu dependency)",
        "accuracy_pct":        accuracy_pct,
        "accuracy_correct":    n_correct,
        "accuracy_total":      n_total,
        "per_class":           per_class,
        "confusion_matrix":    confusion.tolist(),
    }}


