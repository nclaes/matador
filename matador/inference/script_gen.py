def main():
    here = Path(__file__).parent

    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--model", default=str(here / "ta_actions.npy"),
        help="ta_actions.npy or tm_accelerator.v  (default: ta_actions.npy alongside this script)",
    )
    parser.add_argument(
        "--test-data", default={repr(default_test_data)},
        help="Space-separated Boolean test dataset (last column = class label)",
    )
    parser.add_argument(
        "--output", default=str(here / "provenance_report.json"),
        help="Output JSON report path  (default: provenance_report.json alongside this script)",
    )
    args = parser.parse_args()

    model_path    = Path(args.model)
    test_data_path = Path(args.test_data)
    output_path   = Path(args.output)

    if not model_path.exists():
        print(f"ERROR: model file not found: {{model_path}}", file=sys.stderr)
        sys.exit(1)
    if not test_data_path.exists():
        print(f"ERROR: test dataset not found: {{test_data_path}}", file=sys.stderr)
        sys.exit(1)

    # Load
    suffix = model_path.suffix.lower()
    if suffix == ".v":
        print(f"Loading Include-action matrix from Verilog ROM: {{model_path.name}}")
        includes, meta = load_from_verilog(model_path)
    else:
        print(f"Loading Include-action matrix from: {{model_path.name}}")
        includes, meta = load_from_npy(model_path)

    print(f"  {{includes.shape[0]}} classes  |  {{includes.shape[1]}} clauses/class  "
          f"|  {{includes.shape[2]//2}} features")
    print(f"  Non-zero literals: {{includes.sum()}}  /  {{includes.size}}  "
          f"({{100*includes.mean():.1f}}% include rate)")
    print()
    print(f"Running inference on: {{test_data_path.name}}")

    report = build_report(includes, meta, test_data_path, str(model_path.resolve()))

    print(f"  Accuracy : {{report['accuracy_pct']:.2f}}%"
          f"  ({{report['accuracy_correct']}}/{{report['accuracy_total']}})")
    print()
    print("  Per-class accuracy:")
    for cls, res in report["per_class"].items():
        print(f"    class {{cls:>2}}  {{res['accuracy_pct']:6.2f}}%"
              f"  ({{res['correct']}}/{{res['total']}})")
    print()
    print(f"  Model fingerprint : {{report['model_fingerprint']}}")
    print(f"  Dataset SHA-256   : {{report['test_data_sha256']}}")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(report, indent=2, default=str))
    print()
    print(f"Report written to: {{output_path}}")


if __name__ == "__main__":
    main()
