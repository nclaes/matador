def load_from_npy(npy_path: Path):
    """Load the Include-action matrix from the ta_actions.npy companion file.

    ta_actions.npy is a 3-D boolean numpy array written by 'matador train':
      shape: (n_classes, n_clauses_per_class, n_literals)
      dtype: bool
      True  = TA issued Include  (this literal is tested by this clause)
      False = TA issued Exclude  (this literal is ignored by this clause)

    n_literals = 2 × n_features:
      first  n_features positions → positive literals (x_0, x_1, …, x_F-1)
      second n_features positions → negated  literals (~x_0, ~x_1, …, ~x_F-1)

    Returns:
      include_matrix : bool array, shape (n_classes, n_clauses_per_class, n_literals)
      meta           : dict with model parameters (from model_metadata.json if present)
    """
    include_matrix = np.load(str(npy_path)).astype(bool)
    meta_path = npy_path.parent / "model_metadata.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {{}}
    return include_matrix, meta


def load_from_verilog(v_path: Path):
    """Reconstruct the Include-action matrix by parsing the synthesised Verilog ROM.

    Background — how the tile ROM is structured
    --------------------------------------------
    Matador's tiled accelerator stores the Include-action matrix in a 2-D ROM
    indexed by (feat_slice, clause_slice).  Each ROM entry covers a rectangular
    tile of the full (features × clauses) matrix:

      tile_rom[feat_slice * N_CLAUSE_SLICES + clause_slice] = <hex value>
      comment:  // feat_slice=<fi>  clause_slice=<ci>

    Within a tile of width TILE_WIDTH = CLAUSE_SLICE × 2 × FEAT_SLICE bits:

      For each clause k (0 … CLAUSE_SLICE-1) within this tile:
        Global clause index:  g = clause_slice × CLAUSE_SLICE + k

        Positive Include bits for features [fi×FS … (fi+1)×FS - 1]:
          bit position in tile = k × 2 × FEAT_SLICE + l_local

        Negated Include bits for those same features:
          bit position in tile = k × 2 × FEAT_SLICE + FEAT_SLICE + l_local

        where l_local = 0 … FEAT_SLICE-1 (local feature index within the tile column)
        and   feat_global = fi × FEAT_SLICE + l_local (global feature index)

    Redundant (padding) entries
    ---------------------------
    The ROM dimensions are ceiling-divided:
      N_FEAT_SLICES   = ceil(N_FEATURES   / FEAT_SLICE)
      N_CLAUSE_SLICES = ceil(N_CLAUSES_TOTAL / CLAUSE_SLICE)

    So the last feature slice may contain padding feature positions
    (feat_global >= N_FEATURES), and the last clause slice may contain
    padding clause positions (g >= N_CLAUSES_TOTAL).  Both are written
    as zero bits in the ROM.  This function skips them so the recovered
    matrix has exactly N_CLAUSES_TOTAL rows and 2 × N_FEATURES columns —
    no phantom clauses or features are introduced.

    Returns:
      include_matrix : bool array, shape (n_classes, n_clauses_per_class, n_literals)
      meta           : dict with model parameters extracted from the file
    """
    text = v_path.read_text()

    # ── Read model dimensions from the Verilog parameter declarations ──────
    params = {{}}
    for m in re.finditer(r"parameter\\s+(\\w+)\\s*=\\s*(\\d+)", text):
        params[m.group(1)] = int(m.group(2))

    required = ["N_FEATURES", "N_CLASSES", "N_CLAUSES_PC", "N_CLAUSES_TOTAL",
                "FEAT_SLICE", "CLAUSE_SLICE", "N_FEAT_SLICES", "N_CLAUSE_SLICES"]
    missing = [k for k in required if k not in params]
    if missing:
        raise ValueError(
            f"Could not find parameters in {{v_path.name}}: {{missing}}\\n"
            "Make sure the file is a Matador-generated tm_accelerator.v."
        )

    N  = params["N_FEATURES"]       # number of input features
    C  = params["N_CLASSES"]        # number of output classes
    K  = params["N_CLAUSES_PC"]     # clauses per class
    CT = params["N_CLAUSES_TOTAL"]  # = C × K
    FS = params["FEAT_SLICE"]       # feature slice width (tile columns)
    CS = params["CLAUSE_SLICE"]     # clause slice width  (tile rows)

    # ── Allocate the flat Include-action table ─────────────────────────────
    # Rows = one per clause (CT total), columns = one per literal (2 × N).
    # Positive literals occupy columns 0 … N-1, negated literals N … 2N-1.
    include_flat = np.zeros((CT, 2 * N), dtype=bool)

    # ── Parse every tile ROM entry and unpack its bits ─────────────────────
    rom_pattern = re.compile(
        r"tile_rom\\[\\s*(\\d+)\\s*\\]\\s*=\\s*\\d+\\'h([0-9A-Fa-f]+);"
        r"[^\\n]*feat_slice=(\\d+)\\s+clause_slice=(\\d+)"
    )
    for entry in rom_pattern.finditer(text):
        fi       = int(entry.group(3))   # which feature slice column
        ci       = int(entry.group(4))   # which clause slice row
        tile_val = int(entry.group(2), 16)

        for k in range(CS):
            g = ci * CS + k              # global clause index for this slot

            # Skip padding: last clause slice may not be fully used
            if g >= CT:
                continue

            for l_local in range(FS):
                feat_global = fi * FS + l_local   # global feature index

                # Skip padding: last feature slice may not be fully used
                if feat_global >= N:
                    continue

                # Bit positions within the tile entry for this clause/feature
                pos_bit = k * 2 * FS + l_local        # positive literal
                neg_bit = k * 2 * FS + FS + l_local   # negated  literal

                if (tile_val >> pos_bit) & 1:
                    include_flat[g, feat_global] = True          # x[feat_global] included
                if (tile_val >> neg_bit) & 1:
                    include_flat[g, N + feat_global] = True      # ~x[feat_global] included

    # ── Reshape to (n_classes, n_clauses_per_class, n_literals) ───────────
    include_matrix = include_flat.reshape(C, K, 2 * N)

    meta = {{
        "n_features":          N,
        "n_literals":          2 * N,
        "n_classes":           C,
        "n_clauses_total":     CT,
        "n_clauses_per_class": K,
        "model_fingerprint":   "N/A (parsed from Verilog — use ta_actions.npy for fingerprint)",
        "model_variant":       "vanilla",
    }}

    # Supplement with companion metadata.json if it exists nearby
    for candidate in [v_path.parent.parent / "TMIR" / "model_metadata.json",
                      v_path.parent / "model_metadata.json"]:
        if candidate.exists():
            companion = json.loads(candidate.read_text())
            meta["model_fingerprint"] = companion.get("model_fingerprint", meta["model_fingerprint"])
            meta["hyperparameters"]   = companion.get("hyperparameters", {{}})
            meta["provenance"]        = companion.get("provenance", {{}})
            break

    return include_matrix, meta


# ---------------------------------------------------------------------------
# Step 2 — Run inference (identical algorithm to the RTL)
# ---------------------------------------------------------------------------

def run_inference(include_matrix: np.ndarray, features: np.ndarray):
    """Classify a batch of samples using the Include-action matrix.

    This function implements the same three-step algorithm the RTL executes:

    Step A — Build the literal vector
      For each sample, extend the feature vector with its complement:
        literals = [x_0, x_1, …, x_F-1,  ~x_0, ~x_1, …, ~x_F-1]
      The first F positions are the raw feature values (0 or 1).
      The next  F positions are their bitwise negations.

    Step B — Evaluate every clause
      A clause fires (outputs 1) if ALL of its included literals equal 1.
      A clause with no included literals never fires (outputs 0).
      This matches the RTL: an empty clause never contributes to any score.

    Step C — Accumulate per-class scores and take the argmax
      Each class has n_clauses_per_class clauses split into two halves:
        first  half → positive polarity (+1 when it fires)
        second half → negative polarity (-1 when it fires)
      score[c] = Σ(positive clauses that fire) − Σ(negative clauses that fire)
      Predicted class = argmax over scores.

    Args:
      include_matrix : bool, shape (n_classes, n_clauses_per_class, n_literals)
      features       : uint8 0/1, shape (n_samples, n_features)

    Returns:
      predictions : int64, shape (n_samples,)        — predicted class per sample
      scores      : int64, shape (n_samples, n_classes) — raw class scores
    """
    n_classes, n_cpc, n_literals = include_matrix.shape
    n_samples, n_features = features.shape

    # Step A: build literal vector for every sample at once
    literals = np.empty((n_samples, 2 * n_features), dtype=np.uint8)
    literals[:, :n_features] = features          # positive literals
    literals[:, n_features:] = 1 - features      # negated  literals

    # Polarity: +1 for first half of each class's clauses, -1 for second half
    half     = n_cpc // 2
    polarity = np.where(np.arange(n_cpc) < half, 1, -1)

    # Step B: evaluate all clauses in one flat pass for efficiency
    # Flatten to (n_classes × n_cpc, n_literals) so we loop over total clauses
    flat_includes = include_matrix.reshape(-1, n_literals)
    clause_outputs = np.zeros((n_samples, len(flat_includes)), dtype=np.int8)

    for clause_idx, included_literals in enumerate(flat_includes):
        if not included_literals.any():
            # Empty clause: no included literals → always outputs 0
            continue
        # Clause fires if every included literal is 1 in this sample
        clause_outputs[:, clause_idx] = (
            literals[:, included_literals].all(axis=1).astype(np.int8)
        )

    # Step C: reshape back to (n_samples, n_classes, n_cpc) and apply polarity
    clause_outputs = clause_outputs.reshape(n_samples, n_classes, n_cpc)
    scores      = (clause_outputs * polarity[np.newaxis, np.newaxis, :]).sum(axis=2)
    predictions = np.argmax(scores, axis=1)

    return predictions.astype(np.int64), scores.astype(np.int64)


