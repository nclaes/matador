def load_from_npy(npy_path: Path):
    """Load includes from ta_actions.npy.

    Returns (includes, meta) where:
      includes: bool array, shape (n_classes, n_cpc, n_literals)
      meta:     dict from model_metadata.json (or empty dict if absent)
    """
    includes = np.load(str(npy_path)).astype(bool)
    meta_path = npy_path.parent / "model_metadata.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {{}}
    return includes, meta


def load_from_verilog(v_path: Path):
    """Parse a Matador-generated tm_accelerator.v and recover the Include-action matrix.

    The ROM init block has the form:
        tile_rom[<addr>] = <TW>\\'h<hex>;  // feat_slice=<fi> clause_slice=<ci>

    Tile layout per entry at (fi, ci):
        bits [ k*2*FEAT_SLICE         +: FEAT_SLICE ] = positive Include actions, clause k
        bits [ k*2*FEAT_SLICE+FEAT_SLICE +: FEAT_SLICE ] = negated  Include actions, clause k
    where k = 0 .. CLAUSE_SLICE-1 within this tile and clause k+ci*CLAUSE_SLICE globally.

    Returns (includes, meta) where:
      includes: bool array, shape (n_classes, n_cpc, n_literals)
      meta:     dict of extracted parameters
    """
    text = v_path.read_text()

    # Parse module parameters
    params = {{}}
    for m in re.finditer(r"parameter\\s+(\\w+)\\s*=\\s*(\\d+)", text):
        params[m.group(1)] = int(m.group(2))

    required = ["N_FEATURES", "N_CLASSES", "N_CLAUSES_PC", "N_CLAUSES_TOTAL",
                "FEAT_SLICE", "CLAUSE_SLICE", "N_FEAT_SLICES", "N_CLAUSE_SLICES"]
    missing = [k for k in required if k not in params]
    if missing:
        raise ValueError(
            f"Could not find parameters in {{v_path.name}}: {{missing}}\\n"
            "Make sure the file is a Matador-generated tm_accelerator.v."
        )

    N   = params["N_FEATURES"]
    C   = params["N_CLASSES"]
    K   = params["N_CLAUSES_PC"]
    CT  = params["N_CLAUSES_TOTAL"]
    FS  = params["FEAT_SLICE"]
    CS  = params["CLAUSE_SLICE"]

    # Reconstruct ta_actions (n_clauses_total, 2*n_features)
    ta_actions = np.zeros((CT, 2 * N), dtype=bool)

    rom_re = re.compile(
        r"tile_rom\\[\\s*(\\d+)\\s*\\]\\s*=\\s*\\d+\\'h([0-9A-Fa-f]+);"
        r"[^\\n]*feat_slice=(\\d+)\\s+clause_slice=(\\d+)"
    )
    for m in rom_re.finditer(text):
        fi       = int(m.group(3))
        ci       = int(m.group(4))
        tile_val = int(m.group(2), 16)

        for k in range(CS):
            g = ci * CS + k           # global clause index
            if g >= CT:
                continue
            for l_local in range(FS):
                feat_global = fi * FS + l_local
                if feat_global >= N:
                    continue
                pos_bit = k * 2 * FS + l_local
                neg_bit = k * 2 * FS + FS + l_local
                if (tile_val >> pos_bit) & 1:
                    ta_actions[g, feat_global] = True
                if (tile_val >> neg_bit) & 1:
                    ta_actions[g, N + feat_global] = True

    includes = ta_actions.reshape(C, K, 2 * N)

    meta = {{
        "n_features":          N,
        "n_literals":          2 * N,
        "n_classes":           C,
        "n_clauses_total":     CT,
        "n_clauses_per_class": K,
        "model_fingerprint":   "N/A (parsed from Verilog)",
        "model_variant":       "vanilla",
        "hyperparameters":     {{k: params.get(k) for k in
                               ["N_FEATURES", "N_CLASSES", "N_CLAUSES_PC", "N_CLAUSES_TOTAL"]}},
    }}

    # Try to load companion metadata if available
    meta_path = v_path.parent.parent / "TMIR" / "model_metadata.json"
    if not meta_path.exists():
        meta_path = v_path.parent / "model_metadata.json"
    if meta_path.exists():
        companion = json.loads(meta_path.read_text())
        meta["model_fingerprint"] = companion.get("model_fingerprint", meta["model_fingerprint"])
        meta["hyperparameters"]   = companion.get("hyperparameters", meta["hyperparameters"])
        meta["provenance"]        = companion.get("provenance", {{}})

    return includes, meta


# ---------------------------------------------------------------------------
# Inference — identical algorithm to the RTL
# ---------------------------------------------------------------------------

def predict(includes: np.ndarray, X: np.ndarray):
    """Run TM inference from the Include-action matrix.

    Args:
        includes: bool, shape (n_classes, n_clauses_per_class, n_literals)
        X:        uint8 0/1, shape (n_samples, n_features)

    Returns:
        predictions: (n_samples,) int64
        scores:      (n_samples, n_classes) int64

    Convention: a clause with ZERO included literals outputs 0 at inference
    (matches RTL behaviour; differs from TMU training where empty clauses
    output 1 so the regulator can shrink them).
    """
    n_classes, n_cpc, n_literals = includes.shape
    n_samples, n_features = X.shape

    # Build literal matrix: [x_0 ... x_F-1, ~x_0 ... ~x_F-1]
    L = np.empty((n_samples, 2 * n_features), dtype=np.uint8)
    L[:, :n_features] = X
    L[:, n_features:] = 1 - X

    half     = n_cpc // 2
    polarity = np.where(np.arange(n_cpc) < half, 1, -1)   # (n_cpc,)

    # Flatten includes for batch computation
    flat_inc = includes.reshape(-1, n_literals)             # (n_classes*n_cpc, n_literals)
    n_total  = flat_inc.shape[0]

    flat_out = np.zeros((n_samples, n_total), dtype=np.int8)
    for k in range(n_total):
        mask = flat_inc[k]
        if not mask.any():
            continue                                        # empty clause → 0
        flat_out[:, k] = L[:, mask].all(axis=1).astype(np.int8)

    # co: (n_samples, n_classes, n_cpc)
    co     = flat_out.reshape(n_samples, n_classes, n_cpc)
    scores = (co * polarity[np.newaxis, np.newaxis, :]).sum(axis=2)
    preds  = np.argmax(scores, axis=1)
    return preds.astype(np.int64), scores.astype(np.int64)


