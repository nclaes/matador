def main():
    here = Path(__file__).parent

    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--model", default=str(here / "ta_actions.npy"),
        help="ta_actions.npy or tm_accelerator.v  (default: ta_actions.npy alongside this script)",
    )
    parser.add_argument(
        "--test-data", default={repr(default_test_data)},
        help="Space-separated Boolean test dataset (last column = class label)",
    )
    parser.add_argument(
        "--output", default=str(here / "provenance_report.json"),
        help="Output JSON report path  (default: provenance_report.json alongside this script)",
    )
    args = parser.parse_args()

    model_path    = Path(args.model)
    test_data_path = Path(args.test_data)
    output_path   = Path(args.output)

    if not model_path.exists():
        print(f"ERROR: model file not found: {{model_path}}", file=sys.stderr)
        sys.exit(1)
    if not test_data_path.exists():
        print(f"ERROR: test dataset not found: {{test_data_path}}", file=sys.stderr)
        sys.exit(1)

    # Step 1: load the Include-action matrix
    suffix = model_path.suffix.lower()
    if suffix == ".v":
        print(f"Step 1  Loading Include-action matrix from Verilog ROM: {{model_path.name}}")
        include_matrix, meta = load_from_verilog(model_path)
    else:
        print(f"Step 1  Loading Include-action matrix from: {{model_path.name}}")
        include_matrix, meta = load_from_npy(model_path)

    n_cls, n_cpc, n_lit = include_matrix.shape
    print(f"        {{n_cls}} classes  |  {{n_cpc}} clauses/class  |  {{n_lit//2}} features")
    print(f"        {{include_matrix.sum()}} included literals out of {{include_matrix.size}} "
          f"({{100*include_matrix.mean():.1f}}% include rate)")
    print()
    print(f"Step 2  Running inference on: {{test_data_path.name}}")

    # Steps 2+3: inference + report
    report = build_provenance_report(include_matrix, meta, test_data_path, str(model_path.resolve()))

    print(f"        Accuracy : {{report['accuracy_pct']:.2f}}%"
          f"  ({{report['accuracy_correct']}}/{{report['accuracy_total']}} correct)")
    print()
    print("        Per-class accuracy:")
    for cls, res in report["per_class"].items():
        print(f"          class {{cls:>3}}  {{res['accuracy_pct']:6.2f}}%"
              f"  ({{res['correct']}}/{{res['total']}})")
    print()
    print(f"Step 3  Provenance fingerprints")
    print(f"        Model fingerprint : {{report['model_fingerprint']}}")
    print(f"        Dataset SHA-256   : {{report['test_data_sha256']}}")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(report, indent=2, default=str))
    print()
    print(f"Report written to: {{output_path}}")


if __name__ == "__main__":
    main()
