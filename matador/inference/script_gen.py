# Report
# ---------------------------------------------------------------------------

def build_report(includes, meta, test_data_path: Path, model_source: str):
    raw    = np.genfromtxt(str(test_data_path), delimiter=" ", dtype=np.uint32)
    X_test = raw[:, :-1].astype(np.uint8)
    y_test = raw[:, -1].astype(np.int64)

    data_sha256 = hashlib.sha256(test_data_path.read_bytes()).hexdigest()

    preds, scores = predict(includes, X_test)
    correct_mask  = preds == y_test
    n_correct     = int(correct_mask.sum())
    n_total       = len(y_test)
    accuracy_pct  = round(100.0 * n_correct / n_total, 4) if n_total else 0.0

    n_classes = includes.shape[0]
    classes   = sorted(int(c) for c in np.unique(y_test))
    per_class = {{}}
    for cls in classes:
        mask        = y_test == cls
        cls_total   = int(mask.sum())
        cls_correct = int((correct_mask & mask).sum())
        per_class[str(cls)] = {{
            "correct":      cls_correct,
            "total":        cls_total,
            "accuracy_pct": round(100.0 * cls_correct / cls_total, 4) if cls_total else 0.0,
        }}

    cm = np.zeros((n_classes, n_classes), dtype=np.int64)
    for t, p in zip(y_test, preds):
        if 0 <= int(t) < n_classes and 0 <= int(p) < n_classes:
            cm[int(t), int(p)] += 1

    report = {{
        "generated_at":       datetime.now(timezone.utc).isoformat(),
        "python_version":     platform.python_version(),
        "platform":           platform.platform(),
        "model_source":       model_source,
        "model_fingerprint":  meta.get("model_fingerprint", ""),
        "model_variant":      meta.get("model_variant", ""),
        "n_features":         meta.get("n_features", includes.shape[2] // 2),
        "n_classes":          meta.get("n_classes", includes.shape[0]),
        "n_clauses_total":    meta.get("n_clauses_total", includes.shape[0] * includes.shape[1]),
        "n_clauses_per_class":meta.get("n_clauses_per_class", includes.shape[1]),
        "hyperparameters":    meta.get("hyperparameters", {{}}),
        "provenance":         meta.get("provenance", {{}}),
        "test_data_path":     str(test_data_path.resolve()),
        "test_data_sha256":   data_sha256,
        "n_samples":          n_total,
        "inference_engine":   "Pure NumPy — ROM-equivalent (Include-action matrix, no tmu dependency)",
        "accuracy_pct":       accuracy_pct,
        "accuracy_correct":   n_correct,
        "accuracy_total":     n_total,
        "per_class":          per_class,
        "confusion_matrix":   cm.tolist(),
    }}
    return report


